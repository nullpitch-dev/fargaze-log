// Best-guess fallback for unknown food items.
// Returns level2[] using simple substring heuristics over known items,
// else ['Not Defined'] so Hyoje can fix later. Every guess is logged.
function bestGuess(item: string): { level2: string[]; guessed: boolean } {
  // 1. exact
  if (ITEM_MAP[item]) return { level2: ITEM_MAP[item], guessed: false };

  // 2. substring against known items (longest match wins)
  const keys = Object.keys(ITEM_MAP).sort((a, b) => b.length - a.length);
  for (const k of keys) {
    if (k.length >= 2 && item.includes(k)) {
      return { level2: ITEM_MAP[k], guessed: true };
    }
  }

  // 3. give up
  return { level2: ['Not Defined'], guessed: true };
}

